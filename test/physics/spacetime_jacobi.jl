    @testset "the expansion hands over to the AGM continuously" begin
        # the jump is the AGM rounding; the expansion's remainder there is of order ε
        for m1 in (1e-15, 1e-13, 1e-11, 1e-9)
            m = 1 - m1
            us = acosh(sqrt(sqrt(eps()) / (1 - m)))          # (1 − m) cosh²u = √ε
            lo, hi = jacobi_amplitude(prevfloat(us, 4), m), jacobi_amplitude(nextfloat(us, 4), m)
            @test abs(hi - lo) < 1e-13
        end
    end

    @testset "JacobiElliptic wherever its amplitude is exact" begin

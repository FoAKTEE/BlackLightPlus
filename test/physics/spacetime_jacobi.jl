@testset "Jacobi functions near m = 1" begin
    @testset "50-digit values, 1 − m ∈ [1e-15, 1e-8], 0 ≤ u ≤ 2K" begin
        err = 0.0
        for (u, m, sn, cn, dn, am) in JACOBI_REF
            s, c, d = jacobi_sncndn(u, m)
            err = max(err, abs(s - sn), abs(c - cn), abs(d - dn), abs(jacobi_amplitude(u, m) - am))
        end
        @test err < 3e-13
        # the first-order expansion at any u (JacobiElliptic 0.3) is off at the 1e-2 level there
        @test maximum(abs(JacobiElliptic.cn(u, m) - cn) for (u, m, _, cn) in JACOBI_REF) > 1e-2
    end


import numpy as np
# Transcription of GeodesicIntegrator::gluInvertMatrix (symmetric specialization) from the fork
def glu(m):
    inv = np.zeros((4,4))
    inv[0][0] = (m[1][1]*m[2][2]*m[3][3] - m[1][1]*m[2][3]*m[2][3] - m[1][2]*m[1][2]*m[3][3]
                 + m[1][2]*m[1][3]*m[2][3] + m[1][3]*m[1][2]*m[2][3] - m[1][3]*m[1][3]*m[2][2])
    inv[0][1] = (-m[0][1]*m[2][2]*m[3][3] + m[0][1]*m[2][3]*m[2][3] + m[0][2]*m[1][2]*m[3][3]
                 - m[0][2]*m[1][3]*m[2][3] - m[0][3]*m[1][2]*m[2][3] + m[0][3]*m[1][3]*m[2][2])
    inv[0][2] = (m[0][1]*m[1][2]*m[3][3] - m[0][1]*m[2][3]*m[1][3] - m[0][2]*m[1][1]*m[3][3]
                 + m[0][2]*m[1][3]*m[1][3] + m[0][3]*m[1][1]*m[2][3] - m[0][3]*m[1][3]*m[1][2])
    inv[0][3] = (-m[0][1]*m[1][2]*m[2][3] + m[0][1]*m[2][2]*m[1][3] + m[0][2]*m[1][1]*m[2][3]
                 - m[0][2]*m[1][2]*m[1][3] - m[0][3]*m[1][1]*m[2][2] + m[0][3]*m[1][2]*m[1][2])
    inv[1][1] = (m[0][0]*m[2][2]*m[3][3] - m[0][0]*m[2][3]*m[2][3] - m[0][2]*m[0][2]*m[3][3]
                 + m[0][2]*m[0][3]*m[2][3] + m[0][3]*m[0][2]*m[2][3] - m[0][3]*m[0][3]*m[2][2])
    inv[1][2] = (-m[0][0]*m[1][2]*m[3][3] + m[0][0]*m[2][3]*m[1][3] + m[0][2]*m[0][1]*m[3][3]
                 - m[0][2]*m[0][3]*m[1][3] - m[0][3]*m[0][1]*m[2][3] + m[0][3]*m[0][3]*m[1][2])
    inv[1][3] = (m[0][0]*m[1][2]*m[2][3] - m[0][0]*m[2][2]*m[1][3] - m[0][2]*m[0][1]*m[2][3]
                 + m[0][2]*m[0][2]*m[1][3] + m[0][3]*m[0][1]*m[2][2] - m[0][3]*m[0][2]*m[1][2])
    inv[2][2] = (m[0][0]*m[1][1]*m[3][3] - m[0][0]*m[1][3]*m[1][3] - m[0][1]*m[0][1]*m[3][3]
                 + m[0][1]*m[0][3]*m[1][3] + m[0][3]*m[0][1]*m[1][3] - m[0][3]*m[0][3]*m[1][1])
    inv[2][3] = (-m[0][0]*m[1][1]*m[2][3] + m[0][0]*m[1][2]*m[1][3] + m[0][1]*m[0][1]*m[2][3]
                 - m[0][1]*m[0][2]*m[1][3] - m[0][3]*m[0][1]*m[1][2] + m[0][3]*m[0][2]*m[1][1])
    inv[3][3] = (m[0][0]*m[1][1]*m[2][2] - m[0][0]*m[1][2]*m[1][2] - m[0][1]*m[0][1]*m[2][2]
                 + m[0][1]*m[0][2]*m[1][2] + m[0][2]*m[0][1]*m[1][2] - m[0][2]*m[0][2]*m[1][1])
    inv[1][0]=inv[0][1]; inv[2][0]=inv[0][2]; inv[3][0]=inv[0][3]
    inv[2][1]=inv[1][2]; inv[3][1]=inv[1][3]; inv[3][2]=inv[2][3]
    det = m[0][0]*inv[0][0] + m[0][1]*inv[0][1] + m[0][2]*inv[0][2] + m[0][3]*inv[0][3]
    return inv/det
rng = np.random.default_rng(1)
worst = 0.0
for _ in range(2000):
    A = rng.normal(size=(4,4)); m = A + A.T + np.diag([-3,3,3,3])
    err = np.abs(glu(m) @ m - np.eye(4)).max()
    worst = max(worst, err)
print("max |glu(m) m - I| over 2000 random symmetric 4x4:", worst)
